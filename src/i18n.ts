function translateDynamicUi(language: AppLanguage, text: string) {
  const patterns: Array<{ pattern: RegExp; key: string; values: (match: RegExpMatchArray) => Record<string, string> }> = [
    { pattern: /^Minecraft (.+) (fabric|forge|vanilla) profili seçildi\.$/i, key: 'profileSelected', values: (m) => ({ version: m[1], loader: m[2] }) },
    { pattern: /^Minecraft (.+) oturumu kapandı\.$/i, key: 'sessionClosed', values: (m) => ({ username: m[1] }) },
    { pattern: /^Minecraft (.+) oturumu hata koduyla kapandı: (.+)\.$/i, key: 'sessionFailed', values: (m) => ({ username: m[1], code: m[2] }) },
    { pattern: /^Minecraft (.+) için uyumlu yayın bulunamadı\.$/i, key: 'noCompatibleRelease', values: (m) => ({ version: m[1] }) },
    { pattern: /^(.+) zaten yüklü\.$/, key: 'alreadyInstalled', values: (m) => ({ name: m[1] }) },
    { pattern: /^(.+) ve (\d+) gerekli mod eklendi\.$/, key: 'dependenciesInstalled', values: (m) => ({ name: m[1], count: m[2] }) },
    { pattern: /^(.+) eklendi\.$/, key: 'itemInstalled', values: (m) => ({ name: m[1] }) },
    { pattern: /^(.+) kaldırıldı\.$/, key: 'itemRemoved', values: (m) => ({ name: m[1] }) },
    { pattern: /^(.+) \((.+)\) zaten güncel\.$/, key: 'packCurrent', values: (m) => ({ name: m[1], version: m[2] }) },
    { pattern: /^(.+) (.+) sürümü yüklendi\.$/, key: 'packInstalled', values: (m) => ({ name: m[1], version: m[2] }) },
    { pattern: /^(.+) Microsoft hesabıyla giriş yaptı\.$/, key: 'microsoftSignedIn', values: (m) => ({ username: m[1] }) },
  ];

  for (const { pattern, key, values } of patterns) {
    const match = text.match(pattern);
    const template = dynamicUiTemplates[language][key];
    if (!match || !template) continue;
    return template.replace(/\{(\w+)\}/g, (_, name: string) => values(match)[name] ?? '');
  }
  return undefined;
}

export function translateUi(language: AppLanguage, text: string) {
  return translateDynamicUi(language, text)
    ?? uiTranslations[language][text]
    ?? uiTranslations[language][text.trim()]
    ?? (language === 'tr' ? text : uiTranslations.en[text] ?? text);
}
